#!/usr/bin/env node
/**
 * Vantage · tools/bundle.mjs
 * ------------------------------------------------------------------
 * Emits the single-file distribution.
 *
 * Roblox has no package manager story that every developer uses, so the
 * practical distribution for a UI library is one `.luau` file you paste
 * into a ModuleScript. This script produces it from the real source tree
 * — there is no hand-maintained "dist" copy that can drift.
 *
 * What it does, in order:
 *
 *   1. Walks `src/`, resolving `init.luau` into its parent module the way
 *      Rojo does.
 *   2. Builds a dependency graph from every `require(...)` call, tracking
 *      the `local Core = script.Core` alias form as well as direct
 *      `script.Parent.X` chains.
 *   3. Topologically sorts the graph, so the emitted bundle has no
 *      forward references regardless of file order.
 *   4. Rewrites each `require` into a lookup in a tiny module registry.
 *   5. Writes `dist/Vantage.luau` and a string-aware comment-stripped
 *      `dist/Vantage.min.luau`. The stripper walks the source character
 *      by character and never touches the inside of a string, a long
 *      string, or a long comment.
 *
 * Usage:
 *   node tools/bundle.mjs [--check]
 *
 * `--check` verifies the committed bundles are up to date (used by CI).
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, relative, resolve, sep, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const SRC = join(ROOT, "src");
const DIST = join(ROOT, "dist");
const CHECK = process.argv.includes("--check");

const BANNER = `--[[
	VANTAGE ${readVersion()}
	===================================================================
	Interface, engineered.  ·  Single-file distribution.

	DO NOT EDIT THIS FILE.
	======================
	It is generated from src/ by tools/bundle.mjs. Edit the modules in
	src/ and run:

	    node tools/bundle.mjs

	Install
	-------
	Drop this ModuleScript into ReplicatedStorage and require it:

	    local Vantage = require(game.ReplicatedStorage.Vantage)

	Or run it straight from the repository with loadstring:

	    local Vantage = loadstring(game:HttpGet(
	        "https://raw.githubusercontent.com/you/vantage/main/dist/Vantage.luau"
	    ))("Vantage")

	The bundle never dereferences \`script\` — namespace aliases resolve
	through the internal module registry instead — so the same file works
	as a ModuleScript, as a loadstring chunk, and inside a plugin.

	Docs: see README.md and docs/index.html in the repository.
]]

--!nolint
--!nonstrict
`;

function readVersion() {
	try {
		const init = readFileSync(join(SRC, "init.luau"), "utf8");
		const match = init.match(/Vantage\.version\s*=\s*Util\.version/);
		const util = readFileSync(join(SRC, "Core", "Util.luau"), "utf8");
		const v = util.match(/Util\.version\s*=\s*"([^"]+)"/);
		return v ? v[1] : "0.0.0";
	} catch {
		return "0.0.0";
	}
}

/* Collect modules ------------------------------------------------- */

const modules = new Map(); // key -> { body, path, parts }

function keyFor(parts) {
	return parts.length === 0 ? "init" : parts.join(".");
}

function walk(dir, parts) {
	const entries = readdirSync(dir, { withFileTypes: true });
	for (const entry of entries) {
		const abs = join(dir, entry.name);
		if (entry.isDirectory()) {
			if (entry.name.startsWith(".")) continue;
			walk(abs, [...parts, entry.name]);
			continue;
		}
		const match = entry.name.match(/^(.*)\.luau$/);
		if (!match) continue;
		const base = match[1];
		const moduleParts = base === "init" ? parts : [...parts, base];
		const key = keyFor(moduleParts);
		modules.set(key, {
			body: readFileSync(abs, "utf8"),
			path: relative(ROOT, abs).split(sep).join("/"),
			parts: moduleParts,
		});
	}
}

walk(SRC, []);

/* Resolve requires ------------------------------------------------ */

/** Normalises `script.Parent.Parent.Core.Util` style chains. */
function resolveChain(fileParts, chain) {
	const parts = [...fileParts];
	// `script` may be followed by `.Parent` (pop) or `.Name` (push).
	if (chain[0].name !== "script") return null;
	let i = 1;

	// A bare `script` is the module itself.
	while (i < chain.length) {
		const head = chain[i].type === "property" ? chain[i].name : null;
		if (head === null) return null;
		if (head === "Parent") {
			parts.pop();
		} else {
			parts.push(head);
		}
		i += 1;
	}
	return keyFor(parts);
}

/**
 * Finds every `require(<expr>)` in a module and the alias locals that
 * make `<expr>` resolvable.
 */
function analyse(module) {
	const src = module.body;
	const aliases = new Map(); // alias name -> canonical key

	// `local Core = script.Core` / `local Layout = script.Layout`
	const aliasRe = /local\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(script(?:\.[A-Za-z_][A-Za-z0-9_]*)*)\s*\n/g;
	for (const m of src.matchAll(aliasRe)) {
		const chain = parseChain(m[2]);
		const key = resolveChain(module.parts, chain);
		if (key) aliases.set(m[1], key);
	}

	const deps = new Set();
	const requires = [];

	for (const m of src.matchAll(/require\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)/g)) {
		const expr = m[1].trim();
		const chain = parseChain(expr);
		if (!chain) continue;

		let key = null;
		if (chain[0].type === "identifier" && aliases.has(chain[0].name)) {
			// `local Core = script.Core` then `require(Core.Util)` resolves
			// against the alias root, not against this file's own path.
			let resolved = aliases.get(chain[0].name);
			let usable = true;
			for (let i = 1; i < chain.length; i += 1) {
				if (chain[i].type !== "property") {
					usable = false;
					break;
				}
				resolved = resolved === "init" ? chain[i].name : `${resolved}.${chain[i].name}`;
			}
			if (usable) key = resolved;
		} else {
			key = resolveChain(module.parts, chain);
		}
		if (key === null) continue;

		if (key && modules.has(key)) {
			deps.add(key);
			requires.push({ start: m.index, end: m.index + m[0].length, key });
		}
	}

	return { deps, requires };
}

/** Parses `a.b.c` into `[{type:"identifier"|"property", name}]`. */
function parseChain(expr) {
	const trimmed = expr.trim();
	if (!/^[A-Za-z_][A-Za-z0-9_.]*$/.test(trimmed)) return null;
	const pieces = trimmed.split(".");
	return pieces.map((name, index) => ({
		type: index === 0 ? "identifier" : "property",
		name,
	}));
}

const graph = new Map();
const requireMap = new Map();

for (const [key, module] of modules) {
	const { deps, requires, unresolved } = analyse(module);
	if (unresolved) {
		console.error(`bundle: could not resolve a require inside ${module.path}`);
		process.exit(1);
	}
	for (const dep of deps) {
		if (!modules.has(dep)) {
			console.error(`bundle: ${module.path} requires unknown module "${dep}"`);
			process.exit(1);
		}
	}
	graph.set(key, deps);
	requireMap.set(key, requires);
}

/* Topological sort ------------------------------------------------ */

const sorted = [];
const state = new Map(); // key -> "visiting" | "done"

function visit(key, trail = []) {
	const status = state.get(key);
	if (status === "done") return;
	if (status === "visiting") {
		console.error(`bundle: circular require detected: ${[...trail, key].join(" -> ")}`);
		process.exit(1);
	}
	state.set(key, "visiting");
	for (const dep of graph.get(key) ?? []) {
		visit(dep, [...trail, key]);
	}
	state.set(key, "done");
	sorted.push(key);
}

for (const key of [...modules.keys()].sort()) visit(key);

/* Emit ------------------------------------------------------------ */

/** `local Core = script.Core` — the alias form every module uses. */
const ALIAS_RE = /local\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(script(?:\.[A-Za-z_][A-Za-z0-9_]*)*)/g;

function rewrite(module, key) {
	const requires = [...(requireMap.get(key) ?? [])].sort((a, b) => b.start - a.start);
	let src = module.body;
	for (const r of requires) {
		src = src.slice(0, r.start) + `__require(${JSON.stringify(r.key)})` + src.slice(r.end);
	}
	// `local Core = script.Core` → `local Core = __namespace("Core")`.
	// The requires inside the module already resolve through the registry,
	// so nothing in the emitted file needs to touch `script`.
	src = src.replace(ALIAS_RE, (declaration, name, chainText) => {
		const resolved = resolveChain(module.parts, parseChain(chainText));
		if (!resolved) return declaration;
		return `local ${name} = __namespace(${JSON.stringify(resolved)})`;
	});
	// Strip the file-level analysis directive: the bundle carries one.
	src = src.replace(/^--!(strict|nonstrict|nocheck)\s*\n/, "");
	return src.trimEnd();
}

const chunks = [BANNER];

chunks.push(`--[[ Module registry ------------------------------------------------ ]]
-- Modules are emitted in dependency order, so `+"`"+`__require`+"`"+` is always
-- called after its target has been registered.

local __modules: { [string]: () -> any } = {}
local __cache: { [string]: any } = {}

local function __require(path: string): any
	local cached = __cache[path]
	if cached ~= nil then
		return cached
	end
	local loader = __modules[path]
	if loader == nil then
		error("[Vantage] module not found: " .. tostring(path), 2)
	end
	local value = loader()
	if value == nil then
		error("[Vantage] module returned nil: " .. tostring(path), 2)
	end
	__cache[path] = value
	return value
end

-- A namespace alias (local Core = script.Core) becomes a lazy view over
-- the registry instead of the instance tree: the emitted bundle therefore
-- carries no reference to the script global at all, which is what lets one
-- file serve as a ModuleScript *and* as a loadstring chunk.
local function __namespace(prefix: string): any
	return setmetatable({}, {
		__index = function(_, key: string)
			local path = prefix == "" and key or (prefix .. "." .. key)
			if __modules[path] ~= nil then
				return __require(path)
			end
			return nil
		end,
	})
end
`);

for (const key of sorted) {
	const module = modules.get(key);
	chunks.push(`-- ── ${module.path} ${"─".repeat(Math.max(2, 58 - module.path.length))}`);
	chunks.push(`__modules[${JSON.stringify(key)}] = function()`);
	chunks.push(rewrite(module, key));
	chunks.push(`end\n`);
}

chunks.push(`-- ── public API ${"─".repeat(48)}
return __require("init")
`);

const bundle = chunks.join("\n");

/* Minify: conservative, string-aware ------------------------------ */

/**
 * Removes comments. With `blankStrings`, string bodies are blanked too, so
 * the result is *code only* — used for the loadstring guard below, where a
 * mention of `script` inside a string or a doc comment must not count.
 */
function stripComments(src, blankStrings) {
	let out = "";
	let i = 0;
	const n = src.length;
	let lineHasCode = false;

	const isLongOpen = (at) => {
		const m = src.slice(at).match(/^\[(=*)\[/);
		return m ? m[1].length : -1;
	};

	while (i < n) {
		const ch = src[i];
		const next = src[i + 1];

		// Long comment / long string
		if (ch === "-" && next === "-") {
			let j = i + 2;
			if (src[j] === "[") {
				const eq = isLongOpen(j);
				if (eq >= 0) {
					const close = "]" + "=".repeat(eq) + "]";
					const end = src.indexOf(close, j);
					i = end === -1 ? n : end + close.length;
					continue;
				}
			}
			const newline = src.indexOf("\n", i);
			i = newline === -1 ? n : newline;
			continue;
		}

		if (ch === "[") {
			const eq = isLongOpen(i);
			if (eq >= 0) {
				const close = "]" + "=".repeat(eq) + "]";
				const end = src.indexOf(close, i);
				const stop = end === -1 ? n : end + close.length;
				out += blankStrings ? '""' : src.slice(i, stop);
				i = stop;
				lineHasCode = true;
				continue;
			}
		}

		if (ch === '"' || ch === "'") {
			const quote = ch;
			const start = i;
			i += 1;
			while (i < n) {
				if (src[i] === "\\") {
					i += 2;
					continue;
				}
				if (src[i] === quote) {
					i += 1;
					break;
				}
				i += 1;
			}
			out += blankStrings ? '""' : src.slice(start, i);
			lineHasCode = true;
			continue;
		}

		if (ch === "\n") {
			out += "\n";
			lineHasCode = false;
			i += 1;
			continue;
		}

		if (!lineHasCode && (ch === " " || ch === "\t")) {
			i += 1;
			continue;
		}

		lineHasCode = lineHasCode || !/\s/.test(ch);
		out += ch;
		i += 1;
	}

	// Collapse runs of blank lines.
	return out.replace(/\n{3,}/g, "\n\n").replace(/[ \t]+\n/g, "\n");
}

/* Loadstring guard ------------------------------------------------ */

// This file has to run from `loadstring`, where no `script` global exists.
// Aliases are rewritten into registry views above, so a surviving reference
// is a build failure here rather than a crash in somebody's executor.
const executable = stripComments(bundle, true);
const scriptReferences = [...executable.matchAll(/\bscript\b/g)];
if (scriptReferences.length > 0) {
	const at = executable.slice(0, scriptReferences[0].index).split("\n").length;
	console.error(
		"bundle: the emitted bundle dereferences `script` at line " +
			at +
			" of the code-only view — rewrite it as a registry lookup so the file stays loadstring-safe."
	);
	process.exit(1);
}

const minified = stripComments(bundle).trimEnd() + "\n";

/* Write ----------------------------------------------------------- */

mkdirSync(DIST, { recursive: true });

const targets = [
	[join(DIST, "Vantage.luau"), bundle],
	[join(DIST, "Vantage.min.luau"), minified],
	// A copy at the repository root, so a loadstring URL stays short:
	//
	//     loadstring(game:HttpGet(
	//         "https://raw.githubusercontent.com/<user>/<repo>/main/Vantage.luau"
	//     ))()
	//
	// GitHub serves raw files with `text/plain`, which `game:HttpGet`
	// returns verbatim. dist/ remains the canonical artifact.
	[join(ROOT, "Vantage.luau"), bundle],
	// The same bytes under a `.lua` name, because most loader snippets —
	// and most people's muscle memory — expect `.lua` at the end of the
	// URL. Both root names are verified by `tools/verify-http.mjs`.
	[join(ROOT, "Vantage.lua"), bundle],
];

let stale = false;
for (const [path, content] of targets) {
	const existing = existsSync(path) ? readFileSync(path, "utf8") : null;
	if (existing !== content) {
		stale = true;
		if (!CHECK) writeFileSync(path, content);
	}
}

const fullKb = (bundle.length / 1024).toFixed(1);
const minKb = (minified.length / 1024).toFixed(1);
const moduleCount = sorted.length;
const lines = bundle.split("\n").length;

if (CHECK) {
	if (stale) {
		console.error("bundle: dist/ is out of date. Run `node tools/bundle.mjs`.");
		process.exit(1);
	}
	console.log(`bundle: dist/ is up to date (${moduleCount} modules, ${fullKb} KB).`);
} else {
	console.log(
		`bundle: ${moduleCount} modules → ${fullKb} KB (${lines} lines), min ${minKb} KB, ` +
			`order: ${sorted.join(" ")}`
	);
}

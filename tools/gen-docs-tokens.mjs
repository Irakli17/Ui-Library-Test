#!/usr/bin/env node
/**
 * Vantage · tools/gen-docs-tokens.mjs
 * ------------------------------------------------------------------
 * Writes `docs/assets/js/themes.js` from the library itself.
 *
 * The component gallery on GitHub Pages has to look exactly like the
 * library does in-game, which means it must use the same derived tokens —
 * not a hand-copied palette that drifts the first time a theme is tuned.
 * So this runs the real `Theme.derive` for all ten built-ins, prints the
 * colours, and emits them as a JavaScript table.
 *
 * Usage:
 *   node tools/gen-docs-tokens.mjs
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const LUAU = [join(ROOT, ".tools", "luau", "luau.exe"), join(ROOT, ".tools", "luau", "luau")].find((path) =>
	existsSync(path)
);
if (!LUAU) {
	console.error("gen-docs-tokens: install the toolchain first (bash tools/install-toolchain.sh).");
	process.exit(1);
}

const colors = [
	"canvas", "surface", "surfaceAlt", "sunken", "elevated", "raised", "overlay",
	"borderSubtle", "border", "borderStrong", "text", "textMuted", "textDim", "textInverted",
	"hover", "pressed", "trackOff", "knob", "shadow", "scrim",
	"accent", "accentBright", "accentDim", "danger", "success", "warning", "info",
];

const probe = `
local function hex(color)
	return string.format("#%02X%02X%02X",
		math.floor(color.R * 255 + 0.5),
		math.floor(color.G * 255 + 0.5),
		math.floor(color.B * 255 + 0.5))
end

local names = { ${colors.map((name) => `"${name}"`).join(", ")} }
local lines = {}

for _, theme in ipairs(Vantage.Themes()) do
	-- No transition: this only reads the derived table.
	Vantage.SetTheme(theme.name, { transition = false })
	local tokens = Vantage.Theme.current()
	local parts = {}
	for _, key in ipairs(names) do
		local value = tokens[key]
		if typeof(value) == "Color3" then
			table.insert(parts, string.format("%s=%s", key, hex(value)))
		end
	end
	table.insert(lines, string.format(
		"%s\\t%s\\t%s\\t%s\\t%s\\t%s",
		theme.name, theme.mode, theme.label, theme.category, theme.description, table.concat(parts, ";")
	))
end

print(table.concat(lines, "\\n"))
`;

// The mock runtime comes first — the library expects `Instance`, `Color3`,
// `Enum` and `task` to already exist as globals.
const program = [
	readFileSync(join(ROOT, "tests", "Mock", "prelude.luau"), "utf8"),
	"local Vantage = (function()",
	readFileSync(join(ROOT, "Vantage.luau"), "utf8"),
	"end)()",
	"Mock.motion = Vantage.Motion",
	probe,
].join("\n");

const build = join(ROOT, "tests", "build");
mkdirSync(build, { recursive: true });
const out = join(build, "tokens.luau");
writeFileSync(out, program);

const result = spawnSync(LUAU, ["-O2", out], { cwd: ROOT, encoding: "utf8" });
if (result.status !== 0) {
	console.error(result.stdout ?? "");
	console.error(result.stderr ?? "");
	process.exit(1);
}

const rows = (result.stdout ?? "")
	.split("\n")
	.map((line) => line.trim())
	.filter((line) => line.includes("\t") && !line.startsWith("["));

const themes = rows.map((line) => {
	const [name, mode, label, category, description, tokens] = line.split("\t");
	const colors = {};
	for (const entry of tokens.split(";")) {
		const [key, value] = entry.split("=");
		if (key && value) colors[key] = value;
	}
	return { name, mode, label, category, description, colors };
});

if (themes.length === 0) {
	console.error("gen-docs-tokens: the library returned no themes.");
	process.exit(1);
}

const banner = `/**
 * Vantage · docs/assets/js/themes.js
 * ------------------------------------------------------------------
 * GENERATED by tools/gen-docs-tokens.mjs — do not edit by hand.
 *
 * These are the tokens the library derives at runtime, printed here so the
 * documentation page renders the same colours the game does. Regenerate
 * after changing a theme:
 *
 *     node tools/gen-docs-tokens.mjs
 *
 * ${themes.length} themes · ${colors.length} named colours each.
 */

export const THEMES = ${JSON.stringify(themes, null, "\t")};

export const THEME_NAMES = THEMES.map((theme) => theme.name);
`;

writeFileSync(join(ROOT, "docs", "assets", "js", "themes.js"), banner);

console.log(`gen-docs-tokens: wrote ${themes.length} themes (${themes.map((theme) => theme.name).join(", ")})`);
